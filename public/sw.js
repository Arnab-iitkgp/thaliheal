const SHELL_CACHE = "thaliheal-shell-" + VERSION;
const MEDIA_CACHE = "thaliheal-media-v1";
const MEDIA_MAX = 80;
// Single word links that open the app (same list as the rewrites in vercel.json).
const APP_ROUTE = /^\/(index\.html|home|scan|plate|soon|track|profile|ask|zeno|consent|privacy|settings|test|dish-s\d{2})?$/;

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(SHELL_CACHE).then((c) => c.addAll(SHELL.map((u) => new Request(u, { cache: "reload" })))));
});

self.addEventListener("activate", (event) => {
  event.waitUntil((async () => {
    for (const key of await caches.keys()) if (key.startsWith("thaliheal-shell-") && key !== SHELL_CACHE) await caches.delete(key);
    await self.clients.claim();
  })());
});

// Tapping a fun fact notification (Away alerts) brings ThaliHeal back, or opens it.
self.addEventListener("notificationclick", (event) => {
  event.notification.close();
  event.waitUntil((async () => {
    const open = await self.clients.matchAll({ type: "window", includeUncontrolled: true });
    if (open.length) return open[0].focus();
    return self.clients.openWindow("/");
  })());
});

// The page sends this when the person taps "Refresh" on the update bar.
self.addEventListener("message", (event) => { if (event.data === "skip-waiting") self.skipWaiting(); });

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;                       // scans and questions are POSTs: straight to the network
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;
  if (url.pathname.startsWith("/api/")) return;           // never cache AI responses or the AI status check
  if (req.mode === "navigate") { event.respondWith(page(url)); return; }
  if (url.pathname.startsWith("/img/") || url.pathname.startsWith("/fonts/")) { event.respondWith(media(req)); return; }
  event.respondWith(shell(req));
});

// Pages: the cached app shell first (instant open, works offline), else the network, else the offline page.
async function page(url) {
  if (APP_ROUTE.test(url.pathname)) {
    const hit = await caches.match("/index.html", { cacheName: SHELL_CACHE });
    if (hit) return hit;
  }
  try { return await fetch(url.href); }
  catch (e) { return (await caches.match("/offline.html", { cacheName: SHELL_CACHE })) || new Response("You're offline.", { status: 503, headers: { "Content-Type": "text/plain" } }); }
}

// Scripts, data and other shell files: cache first, network if missing (never added to the shell cache by hand).
async function shell(req) {
  const hit = await caches.match(req, { cacheName: SHELL_CACHE, ignoreSearch: true });
  return hit || fetch(req);
}

// App images and fonts: shell copy if there is one, else a small runtime cache.
async function media(req) {
  const hit = (await caches.match(req, { cacheName: SHELL_CACHE })) || (await caches.match(req, { cacheName: MEDIA_CACHE }));
  if (hit) return hit;
  const res = await fetch(req);
  if (res.ok && res.type === "basic") {
    const c = await caches.open(MEDIA_CACHE);
    await c.put(req, res.clone());
    const keys = await c.keys();
    for (const k of keys.slice(0, Math.max(0, keys.length - MEDIA_MAX))) await c.delete(k);
  }
  return res;
}
