// The build step (Vercel runs it on every deploy; npm run dev runs it on start):
//   1. writes public/js/flags.js from AI_ENABLED, so the page knows at once whether scanning is on
//   2. rebuilds public/sw.js (scripts/build-sw.js)
//   node scripts/build.js
"use strict";
const fs = require("fs");
const path = require("path");

const FLAGS = path.join(__dirname, "..", "public", "js", "flags.js");

function aiEnabled() { return String(process.env.AI_ENABLED || "").trim().toLowerCase() === "true"; }

function writeFlags() {
  const ai = aiEnabled();
  const out = `/* Generated by scripts/build.js from the AI_ENABLED environment variable. Do not edit by hand.
   ai: false is scan off mode: no photo scanning, assistant or test mode; everything else works.
   The page still asks /api/ai on start and follows its answer if the two ever disagree. */
window.THALIHEAL_FLAGS = { ai: ${ai} };
document.documentElement.classList.toggle("ai-off", !window.THALIHEAL_FLAGS.ai);
`;
  if (!fs.existsSync(FLAGS) || fs.readFileSync(FLAGS, "utf8") !== out) fs.writeFileSync(FLAGS, out);
  return ai;
}

function build() {
  const ai = writeFlags();
  const sw = require("./build-sw").build();
  return Object.assign({ ai }, sw);
}

if (require.main === module) {
  const r = build();
  console.log(`flags.js: AI ${r.ai ? "on" : "off (scan off mode)"}`);
  console.log(`sw.js built: version ${r.version}, ${r.count} shell files, ${(r.bytes / 1024).toFixed(0)} KB cached on install`);
}
module.exports = { build, aiEnabled };
